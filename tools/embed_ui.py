#!/usr/bin/env python3
"""embed_ui.py web/index.html build/web_ui.h  -> const char SKY_WEB_UI[] = "...";"""
import sys
src, out = sys.argv[1:3]
data = open(src, "rb").read()
with open(out, "w") as f:
    f.write("/* generated by tools/embed_ui.py */\n#pragma once\nstatic const char SKY_WEB_UI[] =\n")
    for line in data.split(b"\n"):
        esc = line.decode("utf-8").replace("\\", "\\\\").replace('"', '\\"')
        f.write('  "%s\\n"\n' % esc)
    f.write(";\n")
