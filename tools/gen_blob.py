#!/usr/bin/env python3
"""Turn the linked hook ELF into a C header the injector embeds (code image only; state is separate).

Usage: gen_blob.py hook.elf hook.o out.h

Fails the build if the object contains any absolute relocation (R_X86_64_64/32/32S),
because those would point at link-time addresses once the blob is copied into the game.
"""
import re, subprocess, sys

elf, obj, out = sys.argv[1:4]

rel = subprocess.run(["readelf", "-rW", obj], capture_output=True, text=True, check=True).stdout
bad = sorted(set(re.findall(r"R_X86_64_(?:64|32S?|GOT\w*|GLOB_DAT)\b", rel)))
bad = [b for b in bad if b not in ("R_X86_64_GOTPCRELX", "R_X86_64_REX_GOTPCRELX", "R_X86_64_GOTPCREL")]
if bad:
    sys.exit("hook object has position-dependent relocations: %s" % ", ".join(bad))

subprocess.run(["objcopy", "-O", "binary", elf, elf + ".bin"], check=True)
blob = open(elf + ".bin", "rb").read()

syms = {}
for line in subprocess.run(["nm", elf], capture_output=True, text=True, check=True).stdout.splitlines():
    p = line.split()
    if len(p) == 3:
        syms[p[2]] = int(p[0], 16)

need = ["_blob_end", "sky_state_ptr", "__data_start", "__data_end", "__bss_start", "__bss_end"]
hooks = [n for n in syms if n.startswith("skyhook_")]
for n in need:
    if n not in syms:
        sys.exit("missing symbol " + n)

# The code image is not writable by the game: refuse anything that would need to be.
if syms["__bss_end"] != syms["__bss_start"]:
    sys.exit("hook has %d bytes of .bss; all mutable state must live in struct sky_hook_state"
             % (syms["__bss_end"] - syms["__bss_start"]))
if syms["__data_end"] - syms["__data_start"] != 8:
    sys.exit("hook .data is %d bytes, expected exactly the 8-byte sky_state_ptr (writable globals or "
             "pointer tables with relocations crept in)" % (syms["__data_end"] - syms["__data_start"]))
if syms["__data_start"] != syms["sky_state_ptr"]:
    sys.exit("sky_state_ptr is not the .data object")
if len(blob) < syms["__data_end"]:
    sys.exit("blob file (%d bytes) is shorter than its .data end (%d)" % (len(blob), syms["__data_end"]))

with open(out, "w") as f:
    f.write("/* generated by tools/gen_blob.py - do not edit */\n#pragma once\n#include <stdint.h>\n")
    f.write("#define SKY_BLOB_FILE_SIZE %d\n" % len(blob))
    f.write("#define SKY_BLOB_STATEPTR_OFF 0x%x\n" % syms["sky_state_ptr"])
    for n in sorted(hooks):
        f.write("#define SKY_BLOB_OFF_%s 0x%x\n" % (n[len("skyhook_"):], syms[n]))
    f.write("static const uint8_t sky_blob_bytes[SKY_BLOB_FILE_SIZE] = {\n")
    for i in range(0, len(blob), 16):
        f.write("  " + ",".join("0x%02x" % b for b in blob[i:i+16]) + ",\n")
    f.write("};\n")
print("blob: %d bytes code image, state ptr @0x%x, %d hooks" % (len(blob), syms["sky_state_ptr"], len(hooks)))
